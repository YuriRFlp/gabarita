import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

const perTheme = z.object({ light: z.string().min(1), dark: z.string().min(1) });
const plainToken = z.object({ name: z.string().min(1), value: z.string().min(1) });
const themedToken = z.object({ name: z.string().min(1), value: perTheme });

export const tokensSchema = z.object({
  color: z.object({ tokens: z.array(themedToken).min(1) }),
  type: z.object({ families: z.record(z.string(), z.string().min(1)) }),
  spacing: z.object({ tokens: z.array(plainToken).min(1) }),
  radius: z.object({ tokens: z.array(plainToken).min(1) }),
  shadow: z.object({ tokens: z.array(themedToken) }),
});

export type DesignTokens = z.infer<typeof tokensSchema>;

export const TOKENS_JSON_PATH = fileURLToPath(new URL('../design/tokens.json', import.meta.url));
export const TOKENS_CSS_PATH = fileURLToPath(
  new URL('../src/shared/ui/styles/tokens.css', import.meta.url),
);

function declarations(entries: ReadonlyArray<readonly [string, string]>, indent: string): string {
  return entries.map(([name, value]) => `${indent}--${name}: ${value};`).join('\n');
}

// The first family in the stack becomes var(--font-face-<name>, ...) so next/font can swap in
// the self-hosted font, keeping the rest of the stack as fallback.
function fontStack(name: string, stack: string): string {
  const [first, ...rest] = stack.split(',').map((part) => part.trim());
  return [`var(--font-face-${name}, ${first})`, ...rest].join(', ');
}

export function generateTokensCss(tokens: DesignTokens): string {
  const themed = (theme: 'light' | 'dark') =>
    [...tokens.color.tokens, ...tokens.shadow.tokens].map(
      (token) => [token.name, token.value[theme]] as const,
    );
  const fixed = [
    ...Object.entries(tokens.type.families).map(
      ([name, stack]) => [`font-${name}`, fontStack(name, stack)] as const,
    ),
    ...tokens.spacing.tokens.map((token) => [token.name, token.value] as const),
    ...tokens.radius.tokens.map((token) => [token.name, token.value] as const),
  ];

  return [
    '/* Generated by scripts/generate-tokens-css.ts from design/tokens.json. Do not edit. */',
    ':root {',
    '  color-scheme: light;',
    declarations(themed('light'), '  '),
    declarations(fixed, '  '),
    '}',
    ':root[data-theme="dark"] {',
    '  color-scheme: dark;',
    declarations(themed('dark'), '  '),
    '}',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme]) {',
    '    color-scheme: dark;',
    declarations(themed('dark'), '    '),
    '  }',
    '}',
    '',
  ].join('\n');
}

export function readTokens(path = TOKENS_JSON_PATH): DesignTokens {
  return tokensSchema.parse(JSON.parse(readFileSync(path, 'utf8')));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TOKENS_CSS_PATH, generateTokensCss(readTokens()));
  console.log(`Generated: ${TOKENS_CSS_PATH}`);
}
