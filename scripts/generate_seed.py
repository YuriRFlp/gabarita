"""Gabarita — generates supabase/seed.sql from data/seed/court_it_taxonomy_v0.2.json.

Usage: python scripts/generate_seed.py
Documentation: docs/03-modelo-de-dados.md (section "Carga inicial")
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data/seed/court_it_taxonomy_v0.2.json"
TARGET = ROOT / "supabase/seed.sql"

EXAM_BOARDS = [
    ("fumarc", "Fundação Mariana Resende Costa", "multiple_choice", 0),
    ("fcc", "Fundação Carlos Chagas", "multiple_choice", 0),
    ("ibfc", "Instituto Brasileiro de Formação e Capacitação", "multiple_choice", 0),
    ("cebraspe", "Cebraspe", "true_false", 1),
    ("vunesp", "Fundação para o Vestibular da Universidade Estadual Paulista", "multiple_choice", 0),
    ("fgv", "Fundação Getulio Vargas", "multiple_choice", 0),
    ("aocp", "Instituto AOCP", "multiple_choice", 0),
]
EXAM_BOARD_BY_NAME = {"Fumarc": "fumarc", "FCC": "fcc", "IBFC": "ibfc", "Cebraspe": "cebraspe",
                      "Vunesp": "vunesp", "FGV": "fgv", "Instituto AOCP": "aocp"}


def q(v):
    """Safe SQL literal for text, number, boolean, null or JSON."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def main():
    d = json.loads(SOURCE.read_text(encoding="utf-8"))
    weights = d["meta"]["target_weights"]
    out = ["-- Generated by scripts/generate_seed.py. Do not edit by hand.", "begin;"]

    for b in EXAM_BOARDS:
        out.append(f"insert into exam_boards values ({', '.join(q(x) for x in b)}) on conflict (id) do nothing;")

    # A rubric's board and essay type come from the exams that use it; an unused rubric fails loudly.
    rubric_owner = {}
    for e in d["exams"]:
        if e["essay"]:
            owner = (EXAM_BOARD_BY_NAME[e["exam_board"]], e["essay"]["type"])
            rid = e["essay"]["rubric"]
            if rubric_owner.setdefault(rid, owner) != owner:
                raise SystemExit(f"rubric {rid}: exams disagree on board/type {rubric_owner[rid]} vs {owner}")

    for rid, definition in d["rubrics"].items():
        board, essay_type = rubric_owner[rid]
        out.append(
            f"insert into rubrics (id, exam_board_id, type, definition) values "
            f"({q(rid)}, {q(board)}, {q(essay_type)}, {q(definition)}) "
            f"on conflict (id) do update set definition = excluded.definition;")

    for e in d["exams"]:
        rubric_id = e["essay"]["rubric"] if e["essay"] else None
        out.append(
            "insert into exams (id, court, year, exam_board_id, position, duration_min, objective, essay, rubric_id, target_weight) values "
            f"({q(e['id'])}, {q(e['court'])}, {e['year']}, {q(EXAM_BOARD_BY_NAME[e['exam_board']])}, {q(e['position'])}, "
            f"{int(e['duration_h'] * 60)}, {q(e['objective'])}, {q(e['essay'])}, {q(rubric_id)}, "
            f"{weights[e['id']]}) on conflict (id) do update set target_weight = excluded.target_weight;")

    sort_order = 0
    for category in ("specific", "general"):
        for t in d["taxonomy"][category]:
            sort_order += 1
            out.append(
                "insert into topics (id, category, name, profile, phase, sort_order) values "
                f"({q(t['id'])}, {q(category)}, {q(t['name'])}, {q(t.get('profile'))}, {q(t['phase'])}, {sort_order}) "
                "on conflict (id) do update set category = excluded.category, name = excluded.name, "
                "profile = excluded.profile, phase = excluded.phase, sort_order = excluded.sort_order;")
            for i, s in enumerate(t["subtopics"], 1):
                out.append(
                    f"insert into subtopics (topic_id, name, sort_order) values ({q(t['id'])}, {q(s)}, {i}) "
                    "on conflict (topic_id, name) do update set sort_order = excluded.sort_order;")
            for eid, value in t["incidence"].items():
                out.append(
                    f"insert into incidences values ({q(eid)}, {q(t['id'])}, {value}) "
                    "on conflict (exam_id, topic_id) do update set value = excluded.value;")

    out.append("commit;")
    TARGET.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{TARGET.relative_to(ROOT)}: {len(out)} lines")


if __name__ == "__main__":
    main()
